def test_legacy_path_matches_frozen_oracle_exactly():
    # Values were generated by the pre-session implementation (commit 621956b)
    # for this fixed snapshot; the legacy-only path must stay bit-identical.
    rng=np.random.default_rng(42)
    concepts=[{'id':i+1,'code':f'C{i+1:02}','title':f'T{i+1}','medium':''} for i in range(7)]
    pairs=[]
    for i in range(7):
        for j in range(i+1,7):
            n=int(rng.integers(20,51));w=int(rng.binomial(n,.5+0.03*(3-i)))
            pairs.append({'id':len(pairs)+1,'left_id':i+1,'right_id':j+1,'left_wins':w,'right_wins':n-w,'source':'s'})
    result=analyze_ranking({'concepts':concepts,'pairs':pairs},1.0,60,20261112)
    for row,ability,(rank,low,high) in zip(result['concepts'],LEGACY_ORACLE['abilities'],LEGACY_ORACLE['ranks']):
        assert row['ability']==ability
        assert row['rank']==rank and abs(row['rank_low']-low)<1e-12 and abs(row['rank_high']-high)<1e-12
        assert row['range_session']==row['range_pair']
