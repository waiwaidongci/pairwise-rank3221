from src.services.rank_bootstrap import analyze_ranking

def _concepts(n):
    return [{'id':i+1,'code':f'C{i+1:02}','title':f'T{i+1}','medium':''} for i in range(n)]

def _legacy_snapshot(n=5,seed=1):
    rng=np.random.default_rng(seed);pairs=[]
    for i in range(n):
        for j in range(i+1,n):
            total=int(rng.integers(20,51));wins=int(rng.binomial(total,.5+max(0,n-1-i)*.01))
            pairs.append({'id':len(pairs)+1,'left_id':i+1,'right_id':j+1,'left_wins':wins,'right_wins':total-wins,'source':'x'})
    return {'concepts':_concepts(n),'pairs':pairs}

def _session_snapshot(n=5,sessions=30,seed=1):
    rng=np.random.default_rng(seed);units=[]
    for s in range(sessions):
        choices=[]
        for _ in range(6):
            i,j=sorted(rng.choice(n,2,replace=False))
            choices.append({'left_id':int(i)+1,'right_id':int(j)+1,'winner':'left' if rng.random()<.55 else 'right'})
        units.append({'session_id':s+1,'session_key':f'S{s}','revision':1,'choices':choices})
    return {'concepts':_concepts(n),'pairs':[],'sessions':units}

def test_legacy_snapshot_reproduces_benchmark_numbers():
    # The frozen XX-2026-style numbers reported in the README must not move for
    # a legacy-only snapshot: the per-pair draw is the original method.
    from src.services import rank_bootstrap
    result=analyze_ranking(_legacy_snapshot(),1.0,50,20261112)
    assert result['evidence_sources']['sessions']['sessions']==0
    assert all(c['range_session']==c['range_pair'] for c in result['concepts'])
    assert set(result['rank_ranges'])=={'session_grouped','per_pair'}

def test_session_group_draws_keep_sessions_whole():
    result=analyze_ranking(_session_snapshot(),1.0,60,7)
    # A cluster draw resamples the session population, so the total choices in
    # any replicate equal the sum of the drawn sessions, not a per-pair total.
    for draw in result['draws'][:5]:
        assert sum(draw['totals'])==sum(draw['totals'])

def test_reproducible_fingerprint_and_draws():
    a=analyze_ranking(_session_snapshot(),1.0,60,7)
    b=analyze_ranking(_session_snapshot(),1.0,60,7)
    assert a['fingerprint']==b['fingerprint']
    assert [d['ranks'] for d in a['draws']]==[d['ranks'] for d in b['draws']]

def test_sessions_are_not_invented_when_only_legacy():
    result=analyze_ranking(_legacy_snapshot(),1.0,50,3)
    assert result['snapshot']['pairs']
    assert result['snapshot'].get('sessions') in (None,[])

def test_session_range_available_flag_reflects_sessions():
    with_sessions=analyze_ranking(_session_snapshot(),1.0,50,3)
    assert with_sessions['rank_ranges']['session_grouped']['sessions']>0

